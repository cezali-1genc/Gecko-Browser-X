    fun forLang(languageTag: String): UiStrings {
        return when (LocaleHelper.resolveLocale(languageTag).language) {
            "tr" -> tr
            "de" -> de
            "fr" -> fr
            "ar" -> ar
            "ru" -> ru
            "es" -> es
            "pt" -> pt
            "zh" -> zh
            "ja" -> ja
            else -> en
        }
    }

